'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const SCRIPT = path.join(__dirname, '..', 'generate-theme.js');
const TOKENS = path.join(__dirname, '..', '..', 'design', 'tokens.json');
const { firstFamily, withBlock, BEGIN, END, OUT } = require(SCRIPT);

// A throw-away site root holding a copy of the committed tokens at design/tokens.json.
function tempSite() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'generate-theme-'));
  fs.mkdirSync(path.join(root, 'design'));
  fs.copyFileSync(TOKENS, path.join(root, 'design', 'tokens.json'));
  const run = (...args) => {
    const r = spawnSync(process.execPath, [SCRIPT, ...args], { cwd: root, encoding: 'utf8' });
    return { status: r.status, out: r.stdout + r.stderr };
  };
  const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
  const write = (rel, text) => {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), text);
  };
  return { root, run, read, write };
}

test('the first family of a stack, unquoted, is what the Wowchemy font TOML takes', () => {
  assert.equal(firstFamily('Montserrat, sans-serif'), 'Montserrat');
  assert.equal(firstFamily("'Roboto Mono', monospace"), 'Roboto Mono');
  assert.equal(firstFamily('"Roboto Mono"'), 'Roboto Mono');
  assert.equal(firstFamily('Roboto'), 'Roboto');
});

test('generates the three files from the tokens, each named after its source and version', () => {
  const site = tempSite();
  const r = site.run('design/tokens.json');
  assert.equal(r.status, 0, r.out);
  assert.match(r.out, /✔ theme: wrote data\/themes\/hedata-epu\.toml, data\/fonts\/hedata-epu\.toml, assets\/scss\/custom\.scss/);

  const theme = site.read(OUT.theme);
  assert.match(theme, /^# Generated by scripts\/generate-theme\.js from design\/tokens\.json — hedata-epu design tokens, version 0\.1\.0\./);
  assert.match(theme, /^name = "hedata-epu"$/m);
  assert.match(theme, /^light = true$/m);
  assert.match(theme, /^primary = "#1565c0"$/m, 'color.light.accent');
  assert.match(theme, /^home_section_even = "#f7f7f7"$/m, 'color.light.bg_alt');
  assert.match(theme, /^\[dark\]$/m);
  assert.match(theme, /^ {2}link = "#bbdefb"$/m, 'color.dark.accent');
  assert.match(theme, /^ {2}background = "#23252f"$/m, 'color.dark.bg');
  assert.doesNotMatch(theme, /^ {2}menu_text = /m, 'dark menu_text stays Wowchemy\'s default');

  const fonts = site.read(OUT.fonts);
  assert.match(fonts, /^# Generated by scripts\/generate-theme\.js from design\/tokens\.json — hedata-epu design tokens, version 0\.1\.0\./);
  assert.match(fonts, /^google_fonts = "family=Montserrat:wght@400;700&family=Roboto\+Mono&family=Roboto:wght@400;700"$/m);
  assert.match(fonts, /^heading_font = "Montserrat"$/m, 'bare family, Wowchemy adds the quotes and the generic family');
  assert.match(fonts, /^mono_font = "Roboto Mono"$/m);

  const scss = site.read(OUT.scss);
  assert.ok(scss.startsWith(BEGIN + '\n// Generated by scripts/generate-theme.js from design/tokens.json — hedata-epu design tokens, version 0.1.0.'));
  assert.ok(scss.trimEnd().endsWith(END));
  assert.match(scss, /^:root \{$/m);
  assert.match(scss, /^ {2}--color-accent: #1565c0;$/m);
  assert.match(scss, /^ {2}--font-mono: 'Roboto Mono', monospace;$/m);
  assert.match(scss, /^ {2}--radius-md: 0\.25rem;$/m);
  assert.match(scss, /^ {2}--space-4: 1\.5rem;$/m);
  assert.match(scss, /^ {2}--chart-1: #1565c0;$/m);
  assert.match(scss, /^body\.dark \{$/m);
  assert.match(scss, /body\.dark \{[^}]*--color-bg: #23252f;/, 'dark colours under body.dark');
});

test('a second run changes nothing and --check passes; a hand edit fails --check naming the file', () => {
  const site = tempSite();
  assert.equal(site.run('design/tokens.json').status, 0);
  const first = Object.values(OUT).map((rel) => site.read(rel));
  assert.equal(site.run('design/tokens.json').status, 0);
  assert.deepEqual(Object.values(OUT).map((rel) => site.read(rel)), first, 'idempotent');

  let r = site.run('--check', 'design/tokens.json');
  assert.equal(r.status, 0, r.out);
  assert.match(r.out, /✔ theme: .* match the hedata-epu 0\.1\.0 tokens/);

  site.write(OUT.theme, site.read(OUT.theme).replace('primary = "#1565c0"', 'primary = "#ff0000"'));
  r = site.run('--check', 'design/tokens.json');
  assert.equal(r.status, 1, r.out);
  assert.match(r.out, /^data\/themes\/hedata-epu\.toml: differs from what hedata-epu 0\.1\.0 tokens generate/m);
  assert.match(r.out, /❌ theme: 1 generated file\(s\) out of date/);
  assert.doesNotMatch(r.out, /custom\.scss: differs/);
});

test('--check fails when a generated file is missing', () => {
  const site = tempSite();
  assert.equal(site.run('design/tokens.json').status, 0);
  fs.unlinkSync(path.join(site.root, OUT.fonts));
  const r = site.run('--check', 'design/tokens.json');
  assert.equal(r.status, 1, r.out);
  assert.match(r.out, /^data\/fonts\/hedata-epu\.toml: differs .*\(or is missing\)$/m);
});

test('custom.scss keeps what is outside the generated block; an edit inside it fails --check', () => {
  const site = tempSite();
  site.write(OUT.scss, '// hand-written\n.hero { padding: 0; }\n');
  assert.equal(site.run('design/tokens.json').status, 0);
  let scss = site.read(OUT.scss);
  assert.ok(scss.startsWith(BEGIN), 'the block goes first');
  assert.ok(scss.endsWith(END + '\n\n// hand-written\n.hero { padding: 0; }\n'), 'hand-written part kept after the block, one blank line between');

  assert.equal(site.run('design/tokens.json').status, 0);
  assert.equal(site.read(OUT.scss), scss, 'a re-run leaves the hand-written part once');
  assert.equal(site.run('--check', 'design/tokens.json').status, 0, 'hand-written outside the block is fine');

  site.write(OUT.scss, scss.replace('--radius-md: 0.25rem;', '--radius-md: 1rem;'));
  const r = site.run('--check', 'design/tokens.json');
  assert.equal(r.status, 1, r.out);
  assert.match(r.out, /^assets\/scss\/custom\.scss: differs/m);

  // Changing the hand-written part leaves the block alone and still passes.
  site.write(OUT.scss, scss + '.more { margin: 0; }\n');
  assert.equal(site.run('--check', 'design/tokens.json').status, 0);
  scss = site.read(OUT.scss);
  assert.equal(scss.split(BEGIN).length, 2, 'one block');
});

test('withBlock: replaces an existing block, refuses a lone marker', () => {
  const block = `${BEGIN}\nnew\n${END}\n`;
  assert.equal(withBlock(null, block), block);
  assert.equal(withBlock('', block), block);
  assert.equal(withBlock(`${BEGIN}\nold\n${END}\n\n.x {}\n`, block), `${block}\n.x {}\n`);
  assert.equal(withBlock('.x {}\n', block), `${block}\n.x {}\n`);
  assert.throws(() => withBlock(`${BEGIN}\nold\n`, block), /one generated-block marker without the other/);
});

test('a missing token fails naming its path', () => {
  const site = tempSite();
  const tokens = JSON.parse(site.read('design/tokens.json'));
  delete tokens.color.dark.accent;
  site.write('design/tokens.json', JSON.stringify(tokens));
  const r = site.run('design/tokens.json');
  assert.equal(r.status, 1, r.out);
  assert.match(r.out, /❌ theme: tokens have no color\.dark\.accent/);
  assert.ok(!fs.existsSync(path.join(site.root, OUT.theme)), 'nothing written');
});
